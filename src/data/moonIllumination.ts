export function moonOn(date: string): MoonDay {
  return MOON_BY_DATE[date] ?? { illumination: 0, phaseAngle: 0 };
}

export function moonPhaseName(phaseAngle: number): string {
  const a = ((phaseAngle % 360) + 360) % 360;
  if (a < 8 || a > 352) return "New Moon";
  if (a < 82) return "Waxing Crescent";
  if (a < 98) return "First Quarter";
  if (a < 172) return "Waxing Gibbous";
  if (a < 188) return "Full Moon";
  if (a < 262) return "Waning Gibbous";
  if (a < 278) return "Last Quarter";
  return "Waning Crescent";
}

/** Sky-darkness wording used on calendar badges. Under 30% is treated as a dark-sky window. */
export function skyDarknessLabel(illumination: number): string {
  if (illumination < 30) return "Dark Skies";
  if (illumination < 60) return "Moonlight Interference";
  return "Bright Moon";
}

export function moonBadge(illumination: number, phaseAngle: number): string {
  const pct = Math.round(illumination);
  return `${pct}% ${moonPhaseName(phaseAngle)} — ${skyDarknessLabel(illumination)}`;
}
